// Helper to construct matrix easily
function makeRolePerms(mapping: Partial<Record<PermissionResource, PermissionAction[]>>): Record<PermissionResource, PermissionAction[]> {
  const result: Record<string, PermissionAction[]> = {};
  for (const res of allResources) {
    if (res === 'dashboard') {
      result[res] = mapping[res] || ['view'];
    } else {
      result[res] = mapping[res] || [];
    }
  }
  return result as Record<PermissionResource, PermissionAction[]>;
}

